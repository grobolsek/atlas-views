"""Plan and write the atlas-views block into a migration file."""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path

from .atlas import Atlas
from .project import (
    BEGIN,
    END,
    MigrationFile,
    ProjectError,
    ViewDef,
    compute_state,
    load_migrations,
    topo_order,
)
from .sqltext import quote_ident

HEADER = "-- Generated by atlas-views from the views folder. Do not edit by hand:\n-- change the view files and run `atlas-views sync --amend` instead."


@dataclass
class SyncPlan:
    target: MigrationFile | None  # None -> create a new file with `atlas migrate new`
    fresh: list[MigrationFile]
    creates: list[tuple[ViewDef, str]] = field(default_factory=list)  # (view, reason)
    drops: list[tuple[str, str]] = field(default_factory=list)  # (name, reason)
    warnings: list[str] = field(default_factory=list)
    refreshed_only_warned: list[str] = field(default_factory=list)

    @property
    def has_view_changes(self) -> bool:
        return bool(self.creates or self.drops)

    @property
    def needs_write(self) -> bool:
        # A fresh Atlas file always gets a (possibly empty) block, which marks it as processed.
        return self.target is not None or self.has_view_changes

    def block(self) -> str:
        lines = [BEGIN, HEADER]
        if not self.has_view_changes:
            lines.append("-- no view changes")
        for name, reason in self.drops:
            lines += [f"-- drop: {name} ({reason})", f"DROP VIEW IF EXISTS {quote_ident(name)};"]
        for view, reason in self.creates:
            lines += [f"-- view: {view.name} ({reason})", view.sql.rstrip().rstrip(";").rstrip() + ";"]
        lines.append(END)
        return "\n".join(lines) + "\n"


def plan_sync(
    files: list[MigrationFile],
    desired: dict[str, ViewDef],
    *,
    amend: bool = False,
    force_new: bool = False,
    refresh: bool = True,
) -> SyncPlan:
    marked = [i for i, f in enumerate(files) if f.has_block]
    if amend:
        if not marked:
            raise ProjectError("nothing to amend: no migration contains an atlas-views block yet")
        last = marked[-1]
        if last != len(files) - 1:
            raise ProjectError(
                f"--amend only rewrites the latest migration, but {files[last].name} is followed by "
                f"{len(files) - 1 - last} newer file(s); run `atlas-views sync` without --amend",
            )
        prev = marked[-2] if len(marked) > 1 else -1
        fresh = files[prev + 1 :]
        state = compute_state(files[:last])
        target: MigrationFile | None = files[last]
    else:
        last = marked[-1] if marked else None
        # Before the first sync nothing counts as fresh: we never touch files that may be applied.
        fresh = files[last + 1 :] if last is not None else []
        state = compute_state(files)
        target = fresh[-1] if fresh and not force_new else None

    if target is not None and target.uses_custom_delimiter:
        raise ProjectError(f"{target.name} uses a custom `-- atlas:delimiter`; run with --new")

    plan = SyncPlan(target=target, fresh=fresh)

    # 1. direct view changes
    changed: dict[str, str] = {}
    for k, v in desired.items():
        old = state.views.get(k)
        if old is None:
            changed[k] = "new"
        elif old.fingerprint != v.fingerprint:
            changed[k] = "changed"
    dropped = [k for k in state.views if k not in desired]

    # 2. table DDL in the fresh migrations
    table_events: dict[str, list[str]] = {}
    for f in fresh:
        for action, table in f.table_changes():
            table_events.setdefault(table.lower(), []).append(f"{action} in {f.name}")

    # 3. views affected by those tables, or by views that change/disappear (transitively)
    affected: dict[str, str] = {}
    for k, v in desired.items():
        if k in changed:
            continue
        hits = sorted(v.idents & table_events.keys())
        if hits:
            t = hits[0]
            affected[k] = f"table `{t}` {table_events[t][0]}"
    moving = set(changed) | set(dropped) | set(affected)
    grew = True
    while grew:
        grew = False
        for k, v in desired.items():
            if k in changed or k in affected:
                continue
            hits = sorted(v.idents & moving)
            if hits:
                dep = hits[0]
                why = "dropped" if dep in dropped else ("changed" if dep in changed else "affected")
                affected[k] = f"depends on view `{dep}`, which is {why}"
                moving.add(k)
                grew = True

    for k in dropped:
        plan.drops.append((state.views[k].name, "removed from views folder"))
    dropped_set = set(dropped)
    for k in affected:
        refs_dropped = desired[k].idents & dropped_set
        if refs_dropped:
            plan.warnings.append(
                f"view `{desired[k].name}` references dropped view `{sorted(refs_dropped)[0]}`; the migration will fail until you fix it",
            )
    if refresh:
        emit = {**changed, **{k: f"refresh: {r}" for k, r in affected.items()}}
        if affected:
            names = ", ".join(desired[k].name for k in affected)
            plan.warnings.append(
                f"{len(affected)} view(s) depend on changed tables/views and are re-created: {names}; "
                "run `atlas-views check` to make sure they still work",
            )
    else:
        emit = dict(changed)
        for k, r in affected.items():
            plan.warnings.append(
                f"view `{desired[k].name}` may be broken ({r}); not refreshed (--no-refresh), run `atlas-views check`",
            )

    order, cycle = topo_order(desired, [k for k in desired if k in emit])
    if cycle:
        plan.warnings.append("circular references between views; emitted in file order")
    plan.creates = [(desired[k], emit[k]) for k in order]
    return plan


def write_plan(plan: SyncPlan, migrations_dir: Path, atlas: Atlas, name: str) -> Path:
    """Write the block and re-hash. Rolls back file changes if anything fails."""
    sum_path = migrations_dir / "atlas.sum"
    sum_backup = sum_path.read_bytes() if sum_path.exists() else None
    created: Path | None = None
    original: str | None = None
    target_path: Path | None = None
    try:
        if plan.target is None:
            before = {p.name for p in migrations_dir.glob("*.sql")}
            atlas.migrate("new", name)
            new = [p for p in migrations_dir.glob("*.sql") if p.name not in before]
            if len(new) != 1:
                raise ProjectError(f"expected `atlas migrate new` to create one file, found {len(new)}")
            created = target_path = new[0]
            current = MigrationFile(target_path, target_path.read_text(encoding="utf-8"))
        else:
            target_path = plan.target.path
            original = target_path.read_text(encoding="utf-8")
            current = MigrationFile(target_path, original)

        base = current.text_without_block.rstrip()
        text = (base + "\n\n" if base else "") + plan.block()
        tmp = target_path.with_suffix(".sql.tmp")
        tmp.write_text(text, encoding="utf-8")
        os.replace(tmp, target_path)
        atlas.migrate("hash")
        # sanity: the file must parse back to exactly what we planned
        check = load_migrations(migrations_dir)
        parsed = next(f for f in check if f.path == target_path)
        if len(parsed.ops) != len(plan.creates) + len(plan.drops):
            raise ProjectError(f"{target_path.name}: written block does not parse back correctly")
        return target_path
    except BaseException:
        if created is not None and created.exists():
            created.unlink()
        if original is not None and target_path is not None:
            target_path.write_text(original, encoding="utf-8")
        if sum_backup is not None:
            sum_path.write_bytes(sum_backup)
        elif sum_path.exists():
            sum_path.unlink()
        raise
